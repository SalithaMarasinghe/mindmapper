-- 4. Channel Metadata Extension on Assistant Conversations
-- Allows tagging conversations by channel ('web', 'whatsapp', 'slack')
-- so WhatsApp threads can be viewed alongside web chats without conflict.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_name = 'assistant_conversations' AND column_name = 'channel'
    ) THEN
        ALTER TABLE assistant_conversations ADD COLUMN channel TEXT DEFAULT 'web';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_name = 'assistant_conversations' AND column_name = 'channel_thread_id'
    ) THEN
        ALTER TABLE assistant_conversations ADD COLUMN channel_thread_id TEXT;
        CREATE INDEX IF NOT EXISTS idx_assistant_conversations_channel_thread
            ON assistant_conversations (channel, channel_thread_id);
    END IF;
END $$;
