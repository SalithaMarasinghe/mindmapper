-- 1. Idempotency & Webhook Deduplication Table
-- Meta Webhook retries on HTTP timeouts or network jitter.
-- Storing processed message IDs (wamid) guarantees that actions and LLM inferences
-- are never duplicated.
CREATE TABLE IF NOT EXISTS whatsapp_processed_messages (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    wamid TEXT NOT NULL UNIQUE,
    from_phone TEXT NOT NULL,
    message_type TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_whatsapp_processed_wamid
    ON whatsapp_processed_messages (wamid);

CREATE INDEX IF NOT EXISTS idx_whatsapp_processed_created
    ON whatsapp_processed_messages (created_at DESC);

-- Enable RLS
ALTER TABLE whatsapp_processed_messages ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow service role full access on whatsapp_processed_messages"
    ON whatsapp_processed_messages
    FOR ALL
    USING (auth.jwt() IS NULL OR auth.role() = 'service_role')
    WITH CHECK (auth.jwt() IS NULL OR auth.role() = 'service_role');


-- 2. Channel Pending Actions (Human-in-the-Loop Proposal Store)
-- Holds structured proposals generated by the agent awaiting user approval
-- via WhatsApp interactive buttons or quick replies.
CREATE TABLE IF NOT EXISTS channel_pending_actions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    channel TEXT NOT NULL DEFAULT 'whatsapp',
    channel_user_id TEXT NOT NULL, -- e.g. sender phone number
    proposal_type TEXT NOT NULL,   -- e.g. 'create_work_event', 'create_task', 'create_meeting_event'
    summary TEXT NOT NULL,
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'expired')),
    expires_at TIMESTAMPTZ NOT NULL DEFAULT (NOW() + INTERVAL '2 hours'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_channel_pending_actions_user_status
    ON channel_pending_actions (user_id, status);

CREATE INDEX IF NOT EXISTS idx_channel_pending_actions_lookup
    ON channel_pending_actions (id, status);

-- Enable RLS
ALTER TABLE channel_pending_actions ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can view their own pending actions"
    ON channel_pending_actions
    FOR SELECT
    USING (auth.uid() = user_id);

CREATE POLICY "Allow service role full access on channel_pending_actions"
    ON channel_pending_actions
    FOR ALL
    USING (auth.jwt() IS NULL OR auth.role() = 'service_role')
    WITH CHECK (auth.jwt() IS NULL OR auth.role() = 'service_role');


-- 3. Unified Channel Audit Log
-- Implements an immutable audit trail of the original request, input type (text/voice),
-- agent reasoning, proposed actions, human approval timestamps, and executed MCP tool calls.
CREATE TABLE IF NOT EXISTS channel_audit_log (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    channel TEXT NOT NULL DEFAULT 'whatsapp',
    channel_user_id TEXT NOT NULL,
    channel_message_id TEXT, -- wamid or platform message ID
    input_type TEXT NOT NULL CHECK (input_type IN ('text', 'voice')),
    raw_user_input TEXT NOT NULL, -- original text or transcribed voice note
    assistant_reply TEXT,
    proposed_actions JSONB DEFAULT '[]'::jsonb,
    approval_status TEXT NOT NULL DEFAULT 'none' CHECK (approval_status IN ('none', 'pending', 'approved', 'rejected', 'auto_executed')),
    executed_tool TEXT,       -- name of MCP tool executed, e.g. 'jarvis_create_work_journal'
    execution_result JSONB,   -- tool execution output or error
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_channel_audit_log_user_time
    ON channel_audit_log (user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_channel_audit_log_channel_msg
    ON channel_audit_log (channel, channel_message_id);

-- Enable RLS
ALTER TABLE channel_audit_log ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can view their own channel audit logs"
    ON channel_audit_log
    FOR SELECT
    USING (auth.uid() = user_id);

